from fastapi import APIRouter
from Backend.schemas import InputData
import pandas as pd
import numpy as np
import joblib
from pathlib import Path

router = APIRouter(tags=["AI Prediction"])

_global_model = None

def load_model():
    global _global_model
    if _global_model is not None:
        return _global_model
    try:
        model_path = Path(__file__).resolve().parent.parent / "Ml_models" / "trained_model.joblib"
        if model_path.exists():
            with model_path.open("rb") as f:
                _global_model = joblib.load(f)
                return _global_model
    except Exception as e:
        print(f"Error loading ML model in ai_prediction: {e}")
    return None

@router.post("/ai-prediction")
@router.post("/api/ai-prediction")
def predict(data: InputData):
    model = load_model()

    rainfall = float(data.Rainfall_mm)
    slope = float(data.Slope_Angle)
    soil_sat = float(data.Soil_Saturation)
    veg_cover = float(data.Vegetation_Cover)
    earthquake = float(data.Earthquake_Activity)
    prox_water = float(data.Proximity_to_Water)
    gravel = int(data.Soil_Type_Gravel)
    sand = int(data.Soil_Type_Sand)
    silt = int(data.Soil_Type_Silt)

    # Normalize soil saturation and vegetation cover to 0-1 ratio if sent as 0-100 percentage
    norm_sat = soil_sat if soil_sat <= 1.0 else soil_sat / 100.0
    norm_veg = veg_cover if veg_cover <= 1.0 else veg_cover / 100.0

    features = pd.DataFrame([{
        "Rainfall_mm": rainfall,
        "Slope_Angle": slope,
        "Soil_Saturation": norm_sat,
        "Vegetation_Cover": norm_veg,
        "Earthquake_Activity": earthquake,
        "Proximity_to_Water": prox_water,
        "Soil_Type_Gravel": gravel,
        "Soil_Type_Sand": sand,
        "Soil_Type_Silt": silt
    }])

    if model is not None:
        try:
            prediction = model.predict(features)
            prob_arr = model.predict_proba(features)[0]
            # Class 1 is the landslide risk probability
            hazard_prob = float(prob_arr[1] if len(prob_arr) > 1 else prob_arr[0]) * 100.0
            pred_class = int(prediction[0])

            # Classify severity
            if hazard_prob >= 75:
                risk_level = "Critical"
                rec = "CRITICAL HAZARD: High probability of slope failure detected. Issue slope warning, alert disaster management teams, and prepare evacuation corridors."
            elif hazard_prob >= 50 or pred_class == 1:
                risk_level = "High"
                rec = "HIGH HAZARD: Elevated slope instability detected. Deploy drone surveillance, inspect drainage channels, and monitor precipitation closely."
            elif hazard_prob >= 28:
                risk_level = "Moderate"
                rec = "MODERATE WATCH: Saturated soil and rain alert active. Restrict heavy transit on vulnerable slopes."
            else:
                risk_level = "Low"
                rec = "LOW HAZARD: Environmental and geological parameters are within stable envelope. Standard monitoring active."

            return {
                "success": True,
                "prediction": pred_class,
                "probability": round(hazard_prob, 1),
                "riskLevel": risk_level,
                "recommendation": rec,
                "message": "Inference generated by trained Random Forest ML model"
            }
        except Exception as e:
            print(f"Error during ML inference: {e}")

    # Heuristic fallback calculation if model invocation fails
    rain_weight = (min(300, rainfall) / 250.0) * 35.0
    slope_weight = (min(65, slope) / 60.0) * 30.0
    sat_weight = norm_sat * 25.0
    eq_weight = (min(7, earthquake) / 7.0) * 15.0
    veg_offset = norm_veg * 15.0
    soil_bonus = 10.0 if silt == 1 else 5.0 if sand == 1 else 0.0

    score = rain_weight + slope_weight + sat_weight + eq_weight - veg_offset + soil_bonus
    hazard_prob = min(99.0, max(5.0, round(score, 1)))
    pred_class = 1 if hazard_prob >= 50.0 else 0

    if hazard_prob >= 75:
        risk_level = "Critical"
        rec = "CRITICAL HAZARD: Immediate slope stabilization advisory active."
    elif hazard_prob >= 50:
        risk_level = "High"
        rec = "HIGH HAZARD: Elevated slope instability detected."
    elif hazard_prob >= 28:
        risk_level = "Moderate"
        rec = "MODERATE WATCH: Periodic geotechnical surveillance advised."
    else:
        risk_level = "Low"
        rec = "LOW HAZARD: Terrain parameters indicate stable ground."

    return {
        "success": True,
        "prediction": pred_class,
        "probability": hazard_prob,
        "riskLevel": risk_level,
        "recommendation": rec,
        "message": "Calculated via fallback heuristic model engine"
    }
